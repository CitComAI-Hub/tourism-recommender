"""Configs for the CitCom TEF cities: base.yaml with the city's area, languages and
paths (data/cities/<city>, git-ignored). Valencia-only parts (GVA heritage
inventory, UPV sculpture campus) are switched off."""
import copy
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
# name: (OSM relation, locality, country, description languages)
CITIES = {
    "brussels": (58274, "Bruxelles - Brussel", "BE", ["en", "fr", "nl"]),
    "mechelen": (412864, "Mechelen", "BE", ["en", "nl"]),
    "eindhoven": (47504, "Eindhoven", "NL", ["en", "nl"]),
    "paris": (71525, "Paris", "FR", ["en", "fr"]),
    "luxembourg": (407489, "Luxembourg", "LU", ["en", "fr", "lb", "de"]),
    "warsaw": (336075, "Warszawa", "PL", ["en", "pl"]),
    "aarhus": (1784663, "Aarhus", "DK", ["en", "da"]),
    "tampere": (3579531, "Tampere", "FI", ["en", "fi"]),
    "copenhagen": (2192363, "København", "DK", ["en", "da"]),
}

base = yaml.safe_load((REPO / "configs" / "base.yaml").read_text(encoding="utf-8"))
for name, (relation, locality, country, langs) in CITIES.items():
    c = copy.deepcopy(base)
    d = f"data/cities/{name}"
    c["data"] = {"raw_dir": f"{d}/raw", "processed_dir": f"{d}/processed"}
    ing = c["ingestion"]
    ing["heritage"]["enabled"] = False
    ing.pop("artwork_collections", None)
    ing.update({"area_relation_id": relation, "area_name": locality, "address_locality": locality,
                "address_country": country, "description_languages": langs})
    ing["dedup"]["report_path"] = f"{d}/processed/dedup_matches.csv"
    c["embeddings"]["output_path"] = f"{d}/processed/embeddings.jsonl"
    c["behaviour"] = {"source": f"Flickr YFCC100M (2004-2014), {locality}"}
    out = REPO / "configs" / "tef" / f"{name}.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text(f"# TEF city {name}: generated by research/make_city_configs.py\n"
                   + yaml.safe_dump(c, allow_unicode=True, sort_keys=False), encoding="utf-8")
    print(out.relative_to(REPO))
